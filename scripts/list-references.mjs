// Writes docs/REFERENCES.md from the source URLs stored in the repo.
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);

async function readJson(path) {
  return JSON.parse(await readFile(new URL(path, root), "utf8"));
}

function add(set, url) {
  if (typeof url === "string" && url.startsWith("https://")) set.add(url);
}

const urls = new Set();
const facts = await readJson("data/content/facts.json");
for (const fact of facts.facts || []) {
  if (fact.status === "verified") add(urls, fact.source?.url);
}
const cards = await readJson("data/content/cards.json");
for (const card of cards.cards || []) {
  if (card.status === "verified") add(urls, card.source?.url);
}
for (const file of ["data/latest.json", "data/storms.json", "data/osdr.json", "data/radlab.json"]) {
  const data = await readJson(file);
  add(urls, data.endpoint);
  add(urls, data.guide);
  add(urls, data.url);
}
const choice = await readJson("data/content/nasa_choice.json");
for (const line of choice.lines || []) add(urls, line.source?.url);

const lines = ["# References", "", "Every https source used by the game, generated by `scripts/list-references.mjs`.", ""];
for (const url of [...urls].sort()) lines.push(`- ${url}`);
lines.push("");
await writeFile(new URL("docs/REFERENCES.md", root), lines.join("\n"));
console.log(`Wrote ${urls.size} references.`);
